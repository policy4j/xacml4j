def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    names: dict[tuple[str, str], str] = {}
    for category in CATEGORIES:
        for variant in variants_for(category):
            name, text = render(variant, category)
            names[(category.key, variant.key)] = name
            (OUT / f"{name}.md").write_text(text, encoding="utf-8")
    current = {f"{name}.md" for name in names.values()}
    removed = remove_stale(OUT, current)

    ntm_text, prompts, ntm_names = render_ntm()
    NTM_ROLES.mkdir(parents=True, exist_ok=True)
    NTM_PERSONAS.write_text(ntm_text, encoding="utf-8")
    NTM_GITIGNORE.write_text(NTM_GITIGNORE_TEXT, encoding="utf-8")
    for name, prompt in prompts.items():
        (NTM_ROLES / f"{name}.md").write_text(prompt, encoding="utf-8")
    removed += remove_stale(NTM_ROLES, {f"{name}.md" for name in prompts})

    README.write_text(render_readme(names, ntm_names), encoding="utf-8")
    print(
        f"wrote {len(names)} CAO profiles, {len(ntm_names)} NTM personas, "
        f"{len(NTM_PERSONA_SETS)} NTM persona sets, and {len(prompts)} prompt "
        f"files; removed {len(removed)} stale files"
    )


def remove_stale(directory: Path, current: set[str]) -> list[str]:
    """Delete generated .md files in directory that are not in current."""
    removed = []
    for path in sorted(directory.glob("*.md")):
        if path.name not in current and path.name.startswith(
            tuple(f"{p}_" for p in GENERATED_PREFIXES)
        ):
            path.unlink()
            removed.append(path.name)
    return removed


if __name__ == "__main__":
    main()
