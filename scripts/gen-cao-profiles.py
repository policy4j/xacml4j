BUILDS = {"build-write", "impl-write"}  # access levels that run Maven


def permission(variant: Variant, category: Category) -> str:
    write = category.access != "read"
    if variant.provider == "claude_code":
        return "acceptEdits" if write else "plan"
    if variant.provider == "codex":
        if category.access in BUILDS:
            return "bypassPermissions"  # Maven must write ~/.m2 and reach the network
        return "acceptEdits" if write else "plan"
    if variant.provider == "antigravity_cli":
        return "acceptEdits" if write else "bypassPermissions"
    return "bypassPermissions"  # kimi_cli, grok_cli: needed for CAO callbacks


# Codex pre-approves an MCP tool only when it is listed by its full name
# (both in the profile and in the launch's allowed tools); a server-level
# "@cao-mcp-server" entry is not enough for assign and handoff.
SUPERVISOR_TOOLS = [
    "mcp__cao-mcp-server__send_message",
    "mcp__cao-mcp-server__assign",
    "mcp__cao-mcp-server__handoff",
]


def allowed_tools(variant: Variant, category: Category) -> list[str]:
    if category.access == "read":
        tools = ["fs_read", "fs_list", "execute_bash", "@cao-mcp-server"]
    else:
        tools = ["@builtin", "fs_*", "execute_bash", "@cao-mcp-server"]
    if category.role == "supervisor" and variant.provider == "codex":
        tools += SUPERVISOR_TOOLS  # CAO validate warns about these names; Codex needs them
    return tools


def variants_for(category: Category) -> list[Variant]:
    if category.variants is None:
        return list(VARIANTS)
    return [v for v in VARIANTS if v.key in category.variants]


def ntm_variants_for(category: Category) -> list[Variant]:
    """Variants that get an NTM persona for this category."""
    out = []
    for v in variants_for(category):
        if v.ntm_agent is None:
            continue
        # A conductor drives tmux through `ntm`; Codex's workspace-write
        # sandbox is not expected to allow that, so NTM conductors are Claude.
        if category.role == "supervisor" and v.ntm_agent != "claude":
            continue
        out.append(v)
    return out


def ntm_prompt(category: Category) -> str:
    """Role prompt shared by every NTM persona of a category."""
    parts = [
        f"# xacml4j {category.title}",
        "",
        "You work on xacml4j, a Java implementation of the OASIS XACML 2.0 and",
        "3.0 specifications (Maven multi-module; moving to JDK 28 early access",
        "with Valhalla, JEP 401 value classes, `--enable-preview`).",
        "",
        COMMON_RULES,
        "",
        ACCESS_TEXT[category.access],
    ]
    if category.access == "read":
        parts.append(NTM_READ_ONLY_NOTE)
    parts += ["", category.ntm_body or category.body, "", NTM_REPORTING, ""]
    return "\n".join(parts)


def toml_str(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)  # valid TOML basic string


def toml_list(values: list[str] | tuple[str, ...]) -> str:
    return "[" + ", ".join(toml_str(v) for v in values) + "]"


def render_ntm() -> tuple[str, dict[str, str], list[str]]:
    """Return (personas.toml text, prompt files by name, persona names)."""
    lines = [
        "# Generated by scripts/gen-cao-profiles.py; edit the script, not this file.",
        "# One base persona per category (policy4j_<category>, "
        f"{NTM_BASE_VARIANT} model) holds the role prompt;",
        "# policy4j_<category>_<variant> personas extend it with another CLI or model.",
        "# Grok and Kimi have no persona (NTM cannot inject their role); spawn them",
        "# with --grok/--kimi and send .ntm/roles/<base>.md via --base-prompt-file.",
        "",
    ]
    prompts: dict[str, str] = {}
    names: list[str] = []
    base_variant = next(v for v in VARIANTS if v.key == NTM_BASE_VARIANT)
    for category in CATEGORIES:
        base = f"{PREFIX}_{category.key}"
        prompt = ntm_prompt(category)
        if "'''" in prompt:
            raise ValueError(f"{base}: prompt must not contain '''")
        prompts[base] = prompt
        names.append(base)
        lines += [
            "[[personas]]",
            f"name = {toml_str(base)}",
            f"agent_type = {toml_str(base_variant.ntm_agent)}",
            f"model = {toml_str(base_variant.ntm_model)}",
            f"reasoning_effort = {toml_str(base_variant.effort)}",
            f"description = {toml_str(f'xacml4j {category.title.lower()}: {category.summary}')}",
            f"tags = {toml_list([PREFIX, category.key])}",
            f"focus_patterns = {toml_list(category.focus)}",
            "system_prompt = '''",
            prompt.rstrip("\n"),
            "'''",
            "",
        ]
        for v in ntm_variants_for(category):
            name = f"{base}_{v.key}"
            names.append(name)
            lines += [
                "[[personas]]",
                f"name = {toml_str(name)}",
                f"extends = {toml_str(base)}",
                f"agent_type = {toml_str(v.ntm_agent)}",
                f"model = {toml_str(v.ntm_model)}",
            ]
            if v.effort:
                lines.append(f"reasoning_effort = {toml_str(v.effort)}")
            lines += [
                f"description = {toml_str(f'xacml4j {category.title.lower()} using {v.label}')}",
                "",
            ]
    known = set(names)
    for set_name, description, members in NTM_PERSONA_SETS:
        full = [f"{PREFIX}_{m}" for m in members]
        missing = [m for m in full if m not in known]
        if missing:
            raise ValueError(f"{set_name}: unknown personas {missing}")
        lines += [
            "[[persona_sets]]",
            f"name = {toml_str(set_name)}",
            f"description = {toml_str(description)}",
            f"personas = {toml_list(full)}",
            "",
        ]
    text = "\n".join(lines)
    tomllib.loads(text)  # fail before writing if the TOML is malformed
    return text, prompts, names


def enforcement_note(variant: Variant, category: Category) -> str:
    if category.access != "read":
        return ""
    if variant.provider in {"kimi_cli", "antigravity_cli"}:
        return (
            "\nThis provider cannot enforce tool restrictions under CAO; the "
            "read-only rule above is binding on you.\n"
        )
    return ""


def yaml_str(value: str) -> str:
    return json.dumps(value)  # JSON strings are valid YAML scalars


def render(variant: Variant, category: Category) -> tuple[str, str]:
    name = f"{PREFIX}_{category.key}_{variant.key}"
    mode = permission(variant, category)
    title = category.title
    if not title[:3].isupper():  # keep acronyms such as JMH
        title = title[0].lower() + title[1:]
    description = (
        f"xacml4j {title} ({'read-only' if category.access == 'read' else 'scoped writes'}) "
        f"using {variant.label}: {category.summary}."
    )
    lines = [
        "---",
        f"name: {name}",
        f"description: {yaml_str(description)}",
        "tags:",
        f"  - {PREFIX}",
        f"  - {category.key}",
        f"  - {variant.key.split('_')[0]}",
        f"provider: {variant.provider}",
        f"role: {category.role}",
        f"model: {yaml_str(variant.model)}",
        f"permissionMode: {mode}",
    ]
    if variant.provider == "codex" and variant.effort:
        lines += ["codexConfig:", f"  model_reasoning_effort: {variant.effort}"]
    if variant.provider == "claude_code" and variant.effort:
        lines += ["claudeConfig:", f"  effort: {variant.effort}"]
    if variant.provider == "grok_cli":
        # CAO's grok_cli provider reads Grok's idle home screen as processing
        # and never auto-answers the per-directory trust dialog, so startup
        # needs time for an operator to unblock it (see CAO_PROFILES.md).
        lines.append("provider_init_timeout: 3600")
    lines.append("allowedTools:")
    lines += [f"  - {yaml_str(t)}" for t in allowed_tools(variant, category)]
    lines += [
        "skills:",
        "  - cao-worker-protocols",
        "mcpServers:",
        "  cao-mcp-server:",
        "    type: stdio",
        "    command: cao-mcp-server",
        "    args: []",
        "---",
        f"# xacml4j {category.title} ({variant.label})",
        "",
        "You work on xacml4j, a Java implementation of the OASIS XACML 2.0 and",
        "3.0 specifications (Maven multi-module; moving to JDK 28 early access",
        "with Valhalla, JEP 401 value classes, `--enable-preview`).",
        "",
        COMMON_RULES,
        "",
        ACCESS_TEXT[category.access],
        enforcement_note(variant, category),
        category.body,
        "",
        REPORTING,
        "",
    ]
    return name, "\n".join(lines)


