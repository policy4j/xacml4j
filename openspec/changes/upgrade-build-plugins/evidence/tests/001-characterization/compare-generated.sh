#!/bin/bash
# Compare two trees of XJC-generated sources (review rv010, finding N1).
# Passes (exit 0) only when both trees hold the same relative file list and every
# differing line is one of the two XJC header comment lines that name the generator
# version and the generation time: with a "// " prefix in Java sources, without it
# inside the XML comment of META-INF/sun-jaxb.episode. Any other difference exits 1; a missing or
# unreadable input, or a failed diff, exits 2.
# Usage: compare-generated.sh <tree-a> <tree-b> [<raw-diff-output>]
set -euo pipefail
a="$1"; b="$2"; out="${3:-/dev/null}"
for d in "$a" "$b"; do
  [ -d "$d" ] && [ -r "$d" ] || { echo "not a readable directory: $d" >&2; exit 2; }
done
inventory() { (cd "$1" && find . -type f -print | LC_ALL=C sort); }
ia=$(inventory "$a") || { echo "cannot list $a" >&2; exit 2; }
ib=$(inventory "$b") || { echo "cannot list $b" >&2; exit 2; }
: > "$out"
if [ "$ia" != "$ib" ]; then
  diff <(printf '%s\n' "$ia") <(printf '%s\n' "$ib") | tee -a "$out" >&2 || true
  echo "file lists differ" >&2
  exit 1
fi
files=0; changed=0; other=0
while IFS= read -r f; do
  files=$((files+1))
  set +e
  d=$(diff "$a/$f" "$b/$f" 2>&1); rc=$?
  set -e
  [ "$rc" -le 1 ] || { echo "diff failed ($rc) on $f: $d" >&2; exit 2; }
  [ "$rc" -eq 0 ] && continue
  changed=$((changed+1))
  printf '=== %s\n%s\n' "$f" "$d" >> "$out"
  # Any diff line other than a changed-text row, a hunk header, or "---" (for example
  # "Binary files ... differ" or "\ No newline at end of file") is a difference (review rv012 N3).
  u=$(printf '%s\n' "$d" | grep -vcE '^([<>] |---$|[0-9]+(,[0-9]+)?[acd][0-9]+(,[0-9]+)?$)' || true)
  n=$(printf '%s\n' "$d" | grep -E '^[<>] ' \
      | grep -vcE '^[<>] (// )?(This file was generated by the Eclipse Implementation of JAXB, v[0-9][0-9.]* ?|Generated on: .*)$' || true)
  n=$((n+u))
  [ "$n" -eq 0 ] || echo "other lines differ in $f: $n" >&2
  other=$((other+n))
done <<< "$ia"
echo "files: $files, files with differences: $changed, other changed lines: $other"
[ "$other" -eq 0 ] || exit 1
