public final class DefaultFunctionInvocation implements FunctionInvocation
{
	private final static Logger LOG = LoggerFactory.getLogger(DefaultFunctionInvocation.class);

	/**
	 * Direct bindings of static one- and two-parameter methods, a {@link Unary} or a {@link Binary}
	 * (designs D15 and D23 of optimize-pdp-evaluation), so building a function provider again binds
	 * nothing again. Only classes of this loader are bound ({@link #isBindable}), so the map keeps no
	 * foreign class from unloading.
	 */
	private static final Map<Method, Optional<Object>> BINDINGS = new ConcurrentHashMap<>();

	private boolean evalContextRequired;
	private PolicyToPlatformFunctionInvocation<ValueExp> invocation;
	private final Class<?> varArgComponentType;
	// a direct call of the method with one or two arguments and their types, or null (designs D15, D23)
	private final Unary unary;
	private final Binary binary;
	private final Class<?> type0;
	private final Class<?> type1;
	// the comparison of the method's bag scan, or null without one, and whether it compares IEEE doubles;
	// read from the annotation once, here, not through its proxy on every scan (designs D7, D29)
	private final BagStorage.Comparison scanComparison;
	private final boolean scanIeee;
	/** The most parameters of a method that is called with its arguments as they are, with no array (design D39) */
	private static final int FIXED_ARITY = 4;

	// the method, without a direct binding: called with up to four arguments as they are, or else with its
	// arguments in one array; and their types; or null (designs D23, D39)
	private final MethodHandle fixed;
	private final MethodHandle spread;
	private final Class<?>[] parameterTypes;
	private final CallShape callShape;
	private final boolean builtIn;
	// the provider instance when it binds literals at call sites (design D6 of add-regex-engine-spi), or null
	private final LiteralBinder binder;

	public enum CallShape { NONE, FIXED, AND, OR, ANY_OF, ALL_OF, ANY_OF_ANY, MAP }

	/** A call of a static method with one argument, generated by {@link LambdaMetafactory}. */
	@FunctionalInterface
	interface Unary
	{
		Object apply(Object arg0) throws Throwable;
	}

	/** A call of a static method with two arguments, generated by {@link LambdaMetafactory}. */
	@FunctionalInterface
	interface Binary
	{
		Object apply(Object arg0, Object arg1) throws Throwable;
	}

	/**
	 * Constructs XACML function invoker
	 *
	 * @param invocation an expression invocation
	 * @param evalContextRequired a flag indicating if method
	 * requires an {@link EvaluationContext} reference
	 */
	public DefaultFunctionInvocation(
			PolicyToPlatformFunctionInvocation<ValueExp> invocation,
			boolean evalContextRequired)
	{
		this(invocation, evalContextRequired, null);
	}

	DefaultFunctionInvocation(
			PolicyToPlatformFunctionInvocation<ValueExp> invocation,
			boolean evalContextRequired, Class<?> varArgComponentType)
	{
		this(invocation, evalContextRequired, varArgComponentType, null, null, null, false, null);
	}

	private DefaultFunctionInvocation(
			PolicyToPlatformFunctionInvocation<ValueExp> invocation,
			boolean evalContextRequired, Class<?> varArgComponentType,
			Object binding, MethodHandle handle, Method method, boolean builtIn, LiteralBinder binder)
	{
		this.invocation = Objects.requireNonNull(invocation, "invocation");
		this.evalContextRequired = evalContextRequired;
		this.varArgComponentType = varArgComponentType;
		this.unary = (binding instanceof Unary u) ? u : null;
		this.binary = (binding instanceof Binary b) ? b : null;
		this.type0 = (binding == null) ? null : method.getParameterTypes()[0];
		this.type1 = (binary == null) ? null : method.getParameterTypes()[1];
		Optional<XacmlFuncBagScan> scan = binary == null ? Optional.empty() : bagScan(method);
		this.scanComparison = scan.map(XacmlFuncBagScan::value).orElse(null);
		this.scanIeee = scan.map(XacmlFuncBagScan::ieee).orElse(false);
		this.fixed = (handle != null && method.getParameterCount() <= FIXED_ARITY) ? handle : null;
		this.spread = (handle != null && fixed == null) ? handle : null;
		this.parameterTypes = (handle == null && binder == null) ? null : method.getParameterTypes();
		this.builtIn = builtIn;
		this.callShape = callShape(method, builtIn, varArgComponentType, fixed);
		this.binder = binder;
	}

	private static CallShape callShape(Method method, boolean builtIn, Class<?> variadic, MethodHandle fixed)
	{
		if(!builtIn) return CallShape.NONE;
		Class<?> provider = method.getDeclaringClass();
		if(provider == LogicalFunctions.class && variadic != null){
			if(method.getName().equals("and")) return CallShape.AND;
			if(method.getName().equals("or")) return CallShape.OR;
		}
		if(provider == HigherOrderFunctions.class && variadic != null){
			if(method.getName().equals("anyOf")) return CallShape.ANY_OF;
			if(method.getName().equals("allOf")) return CallShape.ALL_OF;
			if(method.getName().equals("anyOfAny")) return CallShape.ANY_OF_ANY;
			if(method.getName().equals("map")) return CallShape.MAP;
		}
		return variadic == null && fixed != null ? CallShape.FIXED : CallShape.NONE;
	}

	public CallShape callShape()
	{
		return callShape;
	}

	public boolean isTrustedBuiltIn()
	{
		return builtIn;
	}

	public int fixedArgumentCount()
	{
		return parameterTypes.length - (evalContextRequired ? 1 : 0);
	}

	/** Invokes a proven built-in shape with already evaluated arguments, or the lazy operand list. */
	public ValueExp invokeFast(FunctionSpec spec, EvaluationContext context, List<Expression> operands,
			Expression v0, Expression v1, Expression v2, Expression v3) throws FunctionInvocationException
	{
		if((callShape == CallShape.ANY_OF || callShape == CallShape.ALL_OF
				|| callShape == CallShape.ANY_OF_ANY || callShape == CallShape.MAP)
				&& !(v0 instanceof FunctionReference)){
			return invoke(spec, context, operands.size() == 2 ? Arrays.asList(v0, v1) : Arrays.asList(v0, v1, v2));
		}
		if(callShape == CallShape.FIXED){
			int count = parameterTypes.length;
			Object a0 = evalContextRequired ? context : v0;
			Object a1 = evalContextRequired ? v0 : v1;
			Object a2 = evalContextRequired ? v1 : v2;
			Object a3 = evalContextRequired ? v2 : v3;
			if(count > 0 && !fits(a0, 0) || count > 1 && !fits(a1, 1)
					|| count > 2 && !fits(a2, 2) || count > 3 && !fits(a3, 3)){
				return invoke(spec, context, Arrays.asList(v0, v1, v2, v3).subList(0, fixedArgumentCount()));
			}
			try{
				return switch(count){
					case 0 -> (ValueExp) fixed.invokeExact();
					case 1 -> (ValueExp) fixed.invokeExact(a0);
					case 2 -> (ValueExp) fixed.invokeExact(a0, a1);
					case 3 -> (ValueExp) fixed.invokeExact(a0, a1, a2);
					default -> (ValueExp) fixed.invokeExact(a0, a1, a2, a3);
				};
			}catch(Throwable e){
				throw new FunctionInvocationException(spec, invocationCause(e));
			}
		}
		try{
			return switch(callShape){
				case AND -> LogicalFunctions.and(context, operands);
				case OR -> LogicalFunctions.or(context, operands);
				case ANY_OF -> operands.size() == 2 ? HigherOrderFunctions.anyOfSingle(context, (FunctionReference)v0, v1)
						: HigherOrderFunctions.anyOfPair(context, (FunctionReference)v0, v1, v2);
				case ALL_OF -> operands.size() == 2 ? HigherOrderFunctions.allOfSingle(context, (FunctionReference)v0, v1)
						: HigherOrderFunctions.allOfPair(context, (FunctionReference)v0, v1, v2);
				case ANY_OF_ANY -> operands.size() == 2 ? HigherOrderFunctions.anyOfAnySingle(context, (FunctionReference)v0, v1)
						: HigherOrderFunctions.anyOfAnyPair(context, (FunctionReference)v0, v1, v2);
				case MAP -> operands.size() == 2 ? HigherOrderFunctions.mapSingle(context, (FunctionReference)v0, v1)
						: HigherOrderFunctions.mapPair(context, (FunctionReference)v0, v1, v2);
				default -> throw new IllegalStateException("No fast invocation");
			};
		}catch(Throwable e){
			throw new FunctionInvocationException(spec, invocationCause(e));
		}
	}

	private static Optional<XacmlFuncBagScan> bagScan(Method method)
	{
		Class<?>[] parameters = method.getParameterTypes();
		if (parameters.length != 2 || parameters[0] != parameters[1]
				|| !Modifier.isFinal(parameters[0].getModifiers()) || method.getReturnType() != BooleanVal.class) {
			return Optional.empty();
		}
		return Optional.ofNullable(method.getAnnotation(XacmlFuncBagScan.class));
	}

	/**
	 * Tells whether {@link #scan} compares a bag with this literal: the method declares a bag scan,
	 * and the scan supports the literal's type (designs D7, D41, cycle AO)
	 */
	public boolean canScan(Value<?> literal)
	{
		if (scanComparison == null || !type0.isInstance(literal)) return false;
		if (scanIeee) return literal instanceof DoubleVal;
		return scanComparison == BagStorage.Comparison.EQUAL || literal instanceof IntegerVal || literal instanceof DoubleVal
				|| literal instanceof ISO8601Date || literal instanceof ISO8601DateTime
				|| literal instanceof ISO8601Time time && time.isTimeZoneDefined();
	}

	public BagStorage.Scan scan(FunctionSpec spec, Value<?> literal, BagOfValues bag)
	{
		if (scanComparison == null || !type0.isInstance(literal)) return BagStorage.Scan.NONE;
		try {
			if (scanIeee) {
				return literal instanceof DoubleVal value
						? bag.scanDoubles(scanComparison, value.get()) : BagStorage.Scan.NONE;
			}
			if (scanComparison == BagStorage.Comparison.EQUAL) return bag.scanEqual(literal);
			if (literal instanceof IntegerVal value) return bag.scanIntegers(scanComparison, value.get());
			if (literal instanceof DoubleVal value) return bag.scanDoubles(scanComparison, value.get());
		} catch (Throwable error) {
			throw new FunctionInvocationException(spec, invocationCause(error));
		}
		if (literal instanceof ISO8601Date || literal instanceof ISO8601DateTime || literal instanceof ISO8601Time) {
			try {
				return bag.scanTemporal(scanComparison, literal);
			} catch (Throwable failure) {
				return BagStorage.Scan.NONE;
			}
		}
		return BagStorage.Scan.NONE;
	}

	/**
	 * Creates the invocation of a provider method. A static method with one or two parameters that
	 * the default factory invokes also gets a direct binding (designs D15 and D23 of
	 * optimize-pdp-evaluation); any other static method that the default factory invokes, also one
	 * that needs the {@link EvaluationContext} or is variadic, gets a method handle (design D23),
	 * and so does an instance method of a provider instance, with the instance bound into the
	 * handle (design D3 of add-regex-engine-spi). A custom factory and a method of a class from
	 * another class loader keep the factory's invocation only. A provider instance that is a
	 * {@link LiteralBinder} binds literals at the call sites of its functions (design D6).
	 *
	 * @param factory the invocation factory
	 * @param instance the provider instance, or {@code null} for a static method
	 * @param m the method
	 * @param evalContextRequired whether the method takes the evaluation context first
	 * @param varArgComponentType the component type of a variadic parameter, or {@code null}
	 * @return the invocation
	 */
	static DefaultFunctionInvocation create(FunctionInvocationFactory factory, Object instance, Method m,
			boolean evalContextRequired, Class<?> varArgComponentType)
	{
		PolicyToPlatformFunctionInvocation<ValueExp> invocation = factory.create(instance, m);
		boolean trusted = factory == FunctionInvocationFactory.defaultFactory() && isBindable(m, instance);
		Object binding = (trusted && instance == null && !evalContextRequired && varArgComponentType == null
				&& (m.getParameterCount() == 1 || m.getParameterCount() == 2)) ?
				BINDINGS.computeIfAbsent(m, DefaultFunctionInvocation::bind).orElse(null) :
				null;
		MethodHandle handle = (trusted && binding == null) ? handle(m, instance).orElse(null) : null;
		return new DefaultFunctionInvocation(invocation, evalContextRequired, varArgComponentType, binding, handle, m,
				trusted && XacmlDefaultFunctions.isBuiltIn(m.getDeclaringClass()),
				(trusted && instance instanceof LiteralBinder binder) ? binder : null);
	}

	/**
	 * A generated lambda class stays reachable from its defining loader, so only methods of
	 * classes of this loader are bound: a provider class from another loader stays unloadable.
	 * Only a public method of a public class (and public enclosing classes) is bound: the
	 * reflective call from {@link FunctionInvocationFactory} cannot reach any other, and the
	 * binding must not reach more than it (review RVI1). A hidden class is not bound: the
	 * strongly linked lambda class would keep it from unloading (review RVI3). A static method is
	 * bound without an instance, an instance method with one.
	 */
	private static boolean isBindable(Method m, Object instance)
	{
		return (instance == null) == Modifier.isStatic(m.getModifiers()) && Modifier.isPublic(m.getModifiers())
				&& isPublic(m.getDeclaringClass()) && !m.getDeclaringClass().isHidden()
				&& Arrays.stream(m.getParameterTypes()).noneMatch(Class::isPrimitive)
				&& ValueExp.class.isAssignableFrom(m.getReturnType())
				&& m.getDeclaringClass().getClassLoader() == DefaultFunctionInvocation.class.getClassLoader();
	}

	private static boolean isPublic(Class<?> type)
	{
		for(Class<?> c = type; c != null; c = c.getEnclosingClass()){
			if(!Modifier.isPublic(c.getModifiers())){
				return false;
			}
		}
		return true;
	}

	private static Optional<Object> bind(Method m)
	{
		try{
			MethodHandles.Lookup lookup = MethodHandles.lookup();
			// The generated class casts its arguments to the parameter types: each must be
			// accessible to it, or the call fails where reflection works (review RVI2)
			for(Class<?> type : m.getParameterTypes()){
				lookup.accessClass(type);
			}
			lookup.accessClass(m.getReturnType());
			MethodHandle target = lookup.unreflect(m);
			CallSite site = LambdaMetafactory.metafactory(lookup, "apply",
					MethodType.methodType(m.getParameterCount() == 1 ? Unary.class : Binary.class),
					MethodType.genericMethodType(m.getParameterCount()),
					target, target.type());
			return Optional.of(site.getTarget().invoke());
		}catch(Throwable e){
			LOG.debug("No direct binding for method=\"{}\", the factory's invocation is used", m, e);
			return Optional.empty();
		}
	}

	/**
	 * The method as a handle that takes its arguments as they are when it has up to four parameters
	 * (design D39), or else in one array (design D23 of optimize-pdp-evaluation); an instance method
	 * takes its instance from the handle. No class is generated, so nothing is cached.
	 */
	private static Optional<MethodHandle> handle(Method m, Object instance)
	{
		try{
			int n = m.getParameterCount();
			MethodHandle method = MethodHandles.lookup().unreflect(m);
			MethodHandle handle = ((instance == null) ? method : method.bindTo(instance)).asFixedArity()
					.asType(MethodType.genericMethodType(n).changeReturnType(ValueExp.class));
			return Optional.of(n <= FIXED_ARITY ? handle : handle.asSpreader(Object[].class, n));
		}catch(IllegalAccessException | RuntimeException e){
			return Optional.empty();
		}
	}

	/** @return whether {@link #invokeDirect} calls the method directly (designs D15, D23) */
	public boolean isDirect()
	{
		return unary != null || binary != null;
	}

	/**
	 * Tells whether this invocation calls string-one-and-only, string-normalize-space or
	 * string-normalize-to-lower-case of the engine through the direct binding of its method (design
	 * D45 of optimize-pdp-evaluation). A method is bound once, only for the default factory and a
	 * public static method of this loader ({@link #create}), so the identity of the binding proves
	 * the method; the identity of an invocation would not.
	 *
	 * @return {@code true} when the binding is the one of one of these methods
	 */
	public boolean isShareable()
	{
		Unary u = unary;
		return u != null && Shareable.BOUND.contains(u);
	}

	/** The bindings of the methods whose values a prepared condition shares in a decision (design D45), made on first use */
	private static final class Shareable
	{
		/** The bindings by identity, as {@link #create} gives them; a method that is not found shares nothing */
		static final Set<Object> BOUND = Collections.newSetFromMap(new IdentityHashMap<>());

		static {
			bind(BagFunctions.class, "stringOneAndOnly", BagOfValues.class);
			bind(StringConversionFunctions.class, "normalizeSpace", StringVal.class);
			bind(StringConversionFunctions.class, "normalizeToLowerCase", StringVal.class);
		}

		private static void bind(Class<?> provider, String name, Class<?> parameter)
		{
			try{
				BINDINGS.computeIfAbsent(provider.getMethod(name, parameter), DefaultFunctionInvocation::bind)
						.ifPresent(BOUND::add);
			}catch(NoSuchMethodException e){
				LOG.debug("No method=\"{}\" of provider=\"{}\" to share", name, provider, e);
			}
		}
	}

	/**
	 * Binds a literal first argument of a two-argument call of the function at its call site, when
	 * the provider instance binds literals (design D6 of add-regex-engine-spi). The bound call is
	 * invoked with the evaluated second argument; a failure maps as a failure of
	 * {@link #invokeDirect(FunctionSpec, EvaluationContext, Expression, Expression)} does.
	 *
	 * @param spec the function
	 * @param literal the literal first argument of the call
	 * @return the bound call, or nothing when the provider binds no literal or not this one
	 */
	public Optional<BoundCall> bind(FunctionSpec spec, Value<?> literal)
	{
		int operand = evalContextRequired ? 2 : 1;
		if(binder == null || parameterTypes == null || operand >= parameterTypes.length){
			return Optional.empty();
		}
		Class<?> operandType = parameterTypes[operand];
		return binder.bind(spec.getId(), literal).map(bound -> new BoundCall(){
			@Override
			public <T extends ValueExp> T invoke(EvaluationContext context, Expression argument)
					throws FunctionInvocationException
			{
				if(!operandType.isInstance(argument)){
					@SuppressWarnings("unchecked")
					T result = (T)DefaultFunctionInvocation.this.invoke(spec, context, Arrays.asList(literal, argument));
					return result;
				}
				try{
					return bound.invoke(context, argument);
				}catch(Throwable e){
					throw new FunctionInvocationException(spec, invocationCause(e));
				}
			}
		});
	}

	/**
	 * Calls the method with one evaluated argument, as
	 * {@link #invokeDirect(FunctionSpec, EvaluationContext, Expression, Expression)} calls it with
	 * two (design D23 of optimize-pdp-evaluation).
	 *
	 * @param spec the function
	 * @param context the evaluation context
	 * @param arg0 the evaluated argument
	 * @return the result of the method
	 * @throws FunctionInvocationException if the method fails; its cause is the first
	 * {@link EvaluationException} of the failure chain, or the root cause
	 */
	public ValueExp invokeDirect(FunctionSpec spec, EvaluationContext context, Expression arg0)
			throws FunctionInvocationException
	{
		if(unary == null || !type0.isInstance(arg0)){
			return invoke(spec, context, Collections.singletonList(arg0));
		}
		try{
			return (ValueExp) unary.apply(arg0);
		}catch(Throwable e){
			throw new FunctionInvocationException(spec, invocationCause(e));
		}
	}

	/**
	 * Calls the method with two evaluated arguments, with no argument list, no argument array, and
	 * no reflection (design D15 of optimize-pdp-evaluation). Without a direct binding, or with an
	 * argument that is not of the method's parameter type, the call goes through
	 * {@link #invoke(FunctionSpec, EvaluationContext, List)}, so it fails as before.
	 *
	 * @param spec the function
	 * @param context the evaluation context
	 * @param arg0 the first evaluated argument (a value, or a function reference)
	 * @param arg1 the second evaluated argument
	 * @return the result of the method
	 * @throws FunctionInvocationException if the method fails; its cause is the first
	 * {@link EvaluationException} of the failure chain, or the root cause
	 */
	public ValueExp invokeDirect(FunctionSpec spec, EvaluationContext context, Expression arg0, Expression arg1)
			throws FunctionInvocationException
	{
		if(binary == null || !type0.isInstance(arg0) || !type1.isInstance(arg1)){
			return invoke(spec, context, Arrays.asList(arg0, arg1));
		}
		try{
			return (ValueExp) binary.apply(arg0, arg1);
		}catch(Throwable e){
			throw new FunctionInvocationException(spec, invocationCause(e));
		}
	}

	@Override
	public ValueExp invoke(FunctionSpec spec,
	                       EvaluationContext context, Expression ...params)
			throws FunctionInvocationException{
		return invoke(spec, context, (params == null)?
				Collections.<Expression>emptyList():
					Arrays.asList(params));
	}

	@Override
	public ValueExp invoke(
			FunctionSpec spec,
			EvaluationContext context,
			List<Expression> arguments)
			throws FunctionInvocationException
	{
		Preconditions.checkNotNull(spec, "Function spec is null");
		Preconditions.checkNotNull(context, "Evaluation context is null");
		Preconditions.checkNotNull(arguments, "Arguments list is null");
		if(fixed != null){
			return invokeFixed(spec, context, arguments);
		}
		Object[] params = parameters(spec, context, arguments);
		return (spread != null && fits(params)) ? invokeSpread(spec, params) : invokeFactory(spec, params);
	}

	/** The arguments as the method takes them: the context first if it needs it, the variadic ones in an array. */
	private Object[] parameters(FunctionSpec spec, EvaluationContext context, List<Expression> arguments)
			throws FunctionInvocationException
	{
		try
		{
			int numOfParms = spec.getNumberOfParams();
			Object[] params = new Object[numOfParms + (evalContextRequired?1:0)];
			int startIndex = 0;
			if(evalContextRequired){
				params[0] = context;
				startIndex++;
			}
			copyInto(arguments, 0, params,
					startIndex,
					(spec.isVariadic()?numOfParms - 1:numOfParms));
			if(spec.isVariadic()){
				params[params.length - 1] = varArgs(spec, arguments, numOfParms);
			}
			return params;
		}
		catch(Exception e){
			throw new FunctionInvocationException(spec, invocationCause(e));
		}
	}

	/** The arguments of the variadic parameter, the last of {@code numOfParms}, in an array of its type. */
	private Object[] varArgs(FunctionSpec spec, List<Expression> arguments, int numOfParms)
	{
		Object[] varArgArray = null;
		if(numOfParms <= arguments.size()){
			int size = arguments.size() - (numOfParms - 1) ;
			Expression exp = arguments.get(numOfParms - 1);
			if(varArgComponentType != null){
				varArgArray = (Object[])Array.newInstance(varArgComponentType, size);
			}else if(exp == null){
				varArgArray = (Object[])Array.newInstance(Object.class, size);
			}else {
				varArgArray = (Object[])Array.newInstance(exp.getClass(), size);
			}
			copyInto(arguments, numOfParms - 1, varArgArray, 0, size);
		}
		if(varArgArray == null ||
				(varArgArray.length == 1 && varArgArray[0] == null)){
			// No argument for the variadic parameter; the normalized
			// argument list marks that with a single null. A parameter
			// that allows zero arguments gets an empty array of its
			// type, as a direct Java call passes. A parameter with a
			// minimum keeps null, so a call with too few arguments
			// fails as before and does not compute a value.
			varArgArray = (varArgComponentType != null &&
					spec.getParamSpecAt(numOfParms - 1).isOptional())?
					(Object[])Array.newInstance(varArgComponentType, 0):null;
		}
		return varArgArray;
	}

	/**
	 * Calls a method of up to four parameters with its arguments as they are, with no parameter
	 * array (design D39). The arguments are those of {@link #parameters}; when one does not fit its
	 * parameter, or their number is not the method's, the factory's call is made, which fails as
	 * before.
	 */
	private ValueExp invokeFixed(FunctionSpec spec, EvaluationContext context, List<Expression> arguments)
			throws FunctionInvocationException
	{
		int numOfParms = spec.getNumberOfParams();
		int count = numOfParms + (evalContextRequired?1:0);
		// The variadic arguments are in the array of the last parameter
		int varArgIndex = spec.isVariadic() ? count - 1 : -1;
		Object a0, a1, a2, a3;
		try{
			Object[] varArgs = (varArgIndex >= 0) ? varArgs(spec, arguments, numOfParms) : null;
			a0 = argument(context, arguments, varArgs, varArgIndex, 0, count);
			a1 = argument(context, arguments, varArgs, varArgIndex, 1, count);
			a2 = argument(context, arguments, varArgs, varArgIndex, 2, count);
			a3 = argument(context, arguments, varArgs, varArgIndex, 3, count);
		}catch(Exception e){
			throw new FunctionInvocationException(spec, invocationCause(e));
		}
		if(count != parameterTypes.length || count > 0 && !fits(a0, 0) || count > 1 && !fits(a1, 1)
				|| count > 2 && !fits(a2, 2) || count > 3 && !fits(a3, 3)){
			return invokeFactory(spec, parameters(spec, context, arguments));
		}
		try{
			return switch(count){
				case 0 -> (ValueExp) fixed.invokeExact();
				case 1 -> (ValueExp) fixed.invokeExact(a0);
				case 2 -> (ValueExp) fixed.invokeExact(a0, a1);
				case 3 -> (ValueExp) fixed.invokeExact(a0, a1, a2);
				default -> (ValueExp) fixed.invokeExact(a0, a1, a2, a3);
			};
		}catch(Throwable e){
			throw new FunctionInvocationException(spec, invocationCause(e));
		}
	}

	/** The argument of the method's parameter at {@code index}, as {@link #parameters} places it; none past the last. */
	private Object argument(EvaluationContext context, List<Expression> arguments,
			Object[] varArgs, int varArgIndex, int index, int count)
	{
		if(index >= count){
			return null;
		}
		if(index == varArgIndex){
			return varArgs;
		}
		int i = evalContextRequired ? index - 1 : index;
		return (i < 0) ? context : arguments.get(i);
	}

	/** Whether {@code Method.invoke} takes the argument for the parameter at {@code index}, as {@link #fits(Object[])} */
	private boolean fits(Object argument, int index)
	{
		return index < parameterTypes.length && (argument == null || parameterTypes[index].isInstance(argument));
	}

	private ValueExp invokeFactory(FunctionSpec spec, Object[] params) throws FunctionInvocationException
	{
		try{
			return invocation.invoke(params);
		}catch(Exception e){
			throw new FunctionInvocationException(spec, invocationCause(e));
		}
	}

	/**
	 * Calls the method through its spreading handle (design D23 of optimize-pdp-evaluation), with no
	 * {@code Method.invoke}: a failure builds no {@code InvocationTargetException} and no wrapper of the
	 * factory, and maps as the reflective call's failure does.
	 */
	private ValueExp invokeSpread(FunctionSpec spec, Object[] params) throws FunctionInvocationException
	{
		try{
			return (ValueExp) spread.invokeExact(params);
		}catch(Throwable e){
			throw new FunctionInvocationException(spec, invocationCause(e));
		}
	}

	/**
	 * Whether {@code Method.invoke} takes the arguments: one per parameter, each null or of the
	 * parameter's type (no parameter is primitive). Otherwise the factory's call fails as before.
	 */
	private boolean fits(Object[] params)
	{
		if(params.length != parameterTypes.length){
			return false;
		}
		for(int i = 0; i < params.length; i++){
			if(params[i] != null && !parameterTypes[i].isInstance(params[i])){
				return false;
			}
		}
		return true;
	}

	/**
	 * The first {@link EvaluationException} in the chain keeps its status.
	 * A failure with none stays the root cause and becomes processing-error.
	 */
	private static Throwable invocationCause(Throwable error){
		for(Throwable current = error; current != null; current = current.getCause()){
			if(current instanceof EvaluationException){
				return current;
			}
			if(current.getCause() == current){
				break;
			}
		}
		return Throwables.getRootCause(error);
	}

	/**
	 * Copies elements from a given list to the given array
	 * at the given position
	 *
	 * @param src a source list
	 * @param srcPos a starting position in the list
	 * @param dst a destination array
	 * @param dstPos a destination position in array
	 * @param size a number of elements to copy
	 */
	private static void copyInto(
			List<?> src,
			int srcPos, Object[] dst, int dstPos, int size)
	{
		for(int i = srcPos, j = 0; j < size ; i++ ){
			dst[dstPos + j] = src.get(i);
			j++;
		}
	}
}
